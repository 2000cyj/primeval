//! Agent Data Grid desktop shell: Tauri + Rust backend, React frontend.
//!
//! This crate is glue only. `commands/db.rs` is a thin, typed adapter from IPC
//! to the `ide-db` engine (vendored from OpenIDEA); no domain logic lives here.

mod commands;
mod state;

use state::AppState;
use std::path::PathBuf;
use tauri::Manager;

/// Builds the tauri-specta builder holding every command and exported type.
/// Also used by `export_bindings` (tests) to regenerate `src/bindings.ts`.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    commands::builder().dangerously_cast_bigints_to_number()
}

/// Writes the TypeScript bindings the frontend imports (`src/bindings.ts`).
pub fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default().header(
                "// @ts-nocheck\n/* eslint-disable */\n// Generated by tauri-specta. Do not edit; run `pnpm gen:bindings`.",
            ),
            concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts"),
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();

    tauri::Builder::default()
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            // The data sources, saved passwords and query history live next to
            // the other app data (one folder for all windows of this app).
            let root = app
                .path()
                .app_data_dir()
                .unwrap_or_else(|_| PathBuf::from("."));
            let root = root.join("agent-data-grid");
            std::fs::create_dir_all(&root).ok();
            app.manage(AppState::new(root));
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Agent Data Grid");
}
